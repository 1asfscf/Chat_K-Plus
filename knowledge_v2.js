// v2 전용 응답 함수
window.getResponseV2 = function(input) {
    const q = input.toLowerCase();
    let bestMatch = null;
    let bestScore = 0;

    for (const item of window.knowledgeBaseV2) {
        if (!item.keywords || item.keywords.length === 0) continue;
        let score = 0;
        for (const keyword of item.keywords) {
            if (q.includes(keyword)) {
                score += keyword.length * 3;
            }
        }
        if (score > bestScore) {
            bestScore = score;
            bestMatch = item;
        }
    }

    if (bestMatch && bestScore > 0) {
        return {
            reply: bestMatch.reply,
            table: bestMatch.table || null,
            chart: bestMatch.chart || null,
            suggest: bestMatch.suggest || []
        };
    }
    
    const defaultItem = window.knowledgeBaseV2[window.knowledgeBaseV2.length - 1];
    return {
        reply: defaultItem.reply,
        table: null,
        chart: null,
        suggest: defaultItem.suggest || []
    };
};

// v2 전용 차트 데이터 파싱
window.parseChartDataV2 = function(input) {
    const parts = input.split(/[,，]+/).map(s => s.trim());
    const labels = [];
    const values = [];
    for (const part of parts) {
        const match = part.match(/^(.+?)\s*(\d+)$/);
        if (match) {
            labels.push(match[1].trim());
            values.push(parseInt(match[2]));
        }
    }
    if (labels.length >= 2 && labels.length === values.length) {
        return { labels, values };
    }
    return null;
};
